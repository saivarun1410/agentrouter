import type { AgentSpec, Roster } from '../types.js';
import type { Emitter, PlannedWrite } from './types.js';

const AGENT_DIR = '.claude/agents';

const MANAGED_START = '<!-- agentfit:managed -->';
const MANAGED_END = '<!-- agentfit:end -->';
export const USER_MARKER = '<!-- agentfit:user -->';

/**
 * Renders `.claude/agents/*.md`.
 *
 * These files are build output. The spec in `.agentfit/roster.json` is the
 * source of truth, which is what lets a re-render be safe: everything below the
 * user marker is carried across untouched, and everything above it is
 * regenerated from the spec. Hand edits inside the managed block are lost on
 * the next render by design — `agentfit tune` is how they are meant to persist.
 */
export const claudeCodeEmitter: Emitter = {
  name: 'claude-code',
  plan(roster: Roster, read: (rel: string) => string | null): PlannedWrite[] {
    return roster.agents.map((spec) => {
      const path = `${AGENT_DIR}/${spec.name}.md`;
      const existing = read(path);
      const contents = render(spec, existing);
      return {
        path,
        contents,
        action: existing === null ? 'create' : existing === contents ? 'unchanged' : 'update',
      };
    });
  },
};

export function render(spec: AgentSpec, existing: string | null): string {
  const managed = [
    frontmatter(spec),
    '',
    MANAGED_START,
    `<!-- Generated by ${spec.generator} (spec v${spec.version}). Source of truth: .agentfit/roster.json`,
    `     To change this agent: \`agentfit tune ${spec.id} --constraint "..."\` then \`agentfit render\`. -->`,
    '',
    spec.body,
    '',
    constraintsSection(spec),
    MANAGED_END,
    '',
    USER_MARKER,
    '<!-- Anything below this line is yours and survives `agentfit render`. -->',
  ].join('\n');

  const preserved = preservedUserSection(existing);
  return `${managed}\n${preserved ? `\n${preserved}\n` : ''}`;
}

function frontmatter(spec: AgentSpec): string {
  const lines = [
    '---',
    `name: ${spec.name}`,
    `description: ${escapeScalar(spec.description)}`,
    `tools: ${spec.tools.join(', ')}`,
  ];
  if (spec.model !== 'inherit') lines.push(`model: ${spec.model}`);
  lines.push('---');
  return lines.join('\n');
}

/**
 * User tunings render last so they win on conflict, and they are listed as
 * standing corrections rather than folded into the generated prose — a
 * correction that gets rewritten into the body is a correction that quietly
 * disappears on the next regeneration.
 */
function constraintsSection(spec: AgentSpec): string {
  if (spec.constraints.length === 0) return '';
  return [
    '## Standing corrections',
    '',
    'These were added after this agent was generated. Where they conflict with anything above, they win.',
    '',
    ...spec.constraints.map((c) => `- ${c}`),
    '',
  ].join('\n');
}

function preservedUserSection(existing: string | null): string | null {
  if (!existing) return null;
  const index = existing.indexOf(USER_MARKER);
  if (index === -1) return null;
  const after = existing.slice(index + USER_MARKER.length);
  const withoutHint = after.replace(
    /^\s*<!-- Anything below this line is yours[^>]*-->\s*/,
    '',
  );
  const trimmed = withoutHint.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function escapeScalar(value: string): string {
  const collapsed = value.replace(/\s+/g, ' ').trim();
  return /[:#]/.test(collapsed) ? JSON.stringify(collapsed) : collapsed;
}
